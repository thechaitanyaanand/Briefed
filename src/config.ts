import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { BriefedConfig } from './types.js';

export const DEFAULT_MODELS: Record<BriefedConfig['backend'], string> = {
  ollama: 'llama3',
  anthropic: 'claude-haiku-5-5',
  gemini: 'gemini-2.5-flash',
  none: 'none',
};

// Zero-config default: no API key needed, summaries come from commit messages.
// An API key in the environment upgrades to an LLM backend automatically (see getConfig).
export const DEFAULT_CONFIG: BriefedConfig = {
  target: 'auto',
  backend: 'none',
  model: 'none',
  // days: 0 disables age pruning so a quiet week doesn't wipe the context
  window: { days: 0, entries: 10, maxTotalWords: 1000 },
  ignored: ['*.lock', 'package-lock.json', 'pnpm-lock.yaml', 'dist/', '*.map', '*.min.js', '*.min.css'],
  minDiffLines: 10,
  maxSummaryWords: 250
};

export const CONTEXT_FILE = path.join('.briefed', 'context.md');
const AGENT_FILES = ['CLAUDE.md', 'AGENTS.md', path.join('.github', 'copilot-instructions.md')];
// "@path" is a Claude Code import; other agents see a plain path they can open.
const CONTEXT_LINK = `## Recent upstream changes\nAuto-generated by Briefed from git history (newest first):\n@.briefed/context.md\n`;

/**
 * Returns the absolute path of `.briefed/context.md`, the default target.
 * The directory carries its own `.gitignore` so the file never dirties the working tree
 * or causes merge conflicts between teammates, without touching the repo's .gitignore.
 */
export function resolveTargetFile(cwd: string): string {
  const dir = path.resolve(cwd, '.briefed');
  const ignoreFile = path.join(dir, '.gitignore');
  if (!fs.existsSync(ignoreFile)) {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(ignoreFile, '*\n');
  }
  return path.resolve(cwd, CONTEXT_FILE);
}

/**
 * Points every existing agent file (CLAUDE.md, AGENTS.md, copilot-instructions.md) at the
 * context file. Creates a starter CLAUDE.md if none exist. Returns the files it changed.
 */
export function linkContextFile(cwd: string): string[] {
  const existing = AGENT_FILES.map(f => path.resolve(cwd, f)).filter(f => fs.existsSync(f));
  if (existing.length === 0) {
    const claudePath = path.resolve(cwd, 'CLAUDE.md');
    fs.writeFileSync(claudePath, `# AI Context

## Project Commands
*Placeholder: Replace these with your actual project commands!*
- Build project: \`npm run build\`
- Run test suite: \`npm test\`

## Code Guidelines
*Placeholder: Add your coding standards and preferences here!*

${CONTEXT_LINK}`);
    return [claudePath];
  }

  const linked: string[] = [];
  for (const file of existing) {
    const content = fs.readFileSync(file, 'utf-8');
    if (!content.includes('.briefed/context.md')) {
      fs.writeFileSync(file, `${content.trimEnd()}\n\n${CONTEXT_LINK}`);
      linked.push(file);
    }
  }
  return linked;
}

/**
 * Deep merges target and source objects recursively, without modifying the originals.
 */
function deepMerge<T extends Record<string, any>>(target: T, source: Record<string, any>): T {
  const result = { ...target };
  for (const key of Object.keys(source)) {
    // Prevent Prototype Pollution
    if (key === '__proto__' || key === 'constructor') {
      continue;
    }
    const val = source[key];
    if (val !== undefined) {
      if (val && typeof val === 'object' && !Array.isArray(val)) {
        if (result[key] && typeof result[key] === 'object' && !Array.isArray(result[key])) {
          result[key as keyof T] = deepMerge(result[key], val);
        } else {
          result[key as keyof T] = deepMerge({} as any, val) as any;
        }
      } else {
        result[key as keyof T] = val;
      }
    }
  }
  return result;
}

/**
 * Load .briefed.json from cwd (default process.cwd()).
 * If not found or invalid, merge defaults.
 * Performs a DEEP MERGE with the DEFAULT_CONFIG.
 * If target is 'auto', call resolveTargetFile. Otherwise, resolve target path to absolute path.
 * Resolve apiKey in order: user config field -> process.env.BRIEFED_API_KEY -> process.env.ANTHROPIC_API_KEY -> undefined.
 */
export function getConfig(cwd?: string): BriefedConfig {
  const actualCwd = cwd || process.cwd();

  // Start with built-in DEFAULT_CONFIG
  let merged: BriefedConfig = JSON.parse(JSON.stringify(DEFAULT_CONFIG));

  // Global configuration file: ~/.briefed.json
  const globalConfigPath = path.join(os.homedir(), '.briefed.json');
  let globalConfig: any = {};
  if (fs.existsSync(globalConfigPath)) {
    try {
      const content = fs.readFileSync(globalConfigPath, 'utf-8');
      globalConfig = JSON.parse(content);
    } catch (e) {
      // If invalid/malformed JSON, fallback to empty object
      globalConfig = {};
    }
  }
  merged = deepMerge(merged, globalConfig);

  // Local configuration file: .briefed.json in cwd
  const localConfigPath = path.resolve(actualCwd, '.briefed.json');
  let localConfig: any = {};
  if (fs.existsSync(localConfigPath)) {
    try {
      const content = fs.readFileSync(localConfigPath, 'utf-8');
      localConfig = JSON.parse(content);
    } catch (e) {
      // If invalid/malformed JSON, fallback to empty object
      localConfig = {};
    }
  }
  merged = deepMerge(merged, localConfig);

  // Target path resolution
  if (merged.target === 'auto') {
    merged.target = resolveTargetFile(actualCwd);
  } else {
    const resolvedTarget = path.resolve(actualCwd, merged.target);
    const relative = path.relative(actualCwd, resolvedTarget);
    if (relative.startsWith('..') || path.isAbsolute(relative)) {
      throw new Error('Security Error: Target path must reside within the workspace directory.');
    }
    merged.target = resolvedTarget;
  }

  // Auto-detect backend if not explicitly set in local or global configs
  const hasConfiguredBackend = (localConfig.backend !== undefined) || (globalConfig.backend !== undefined);
  if (!hasConfiguredBackend) {
    if (process.env.GEMINI_API_KEY) {
      merged.backend = 'gemini';
    } else if (process.env.BRIEFED_API_KEY || process.env.ANTHROPIC_API_KEY) {
      merged.backend = 'anthropic';
    }
  }

  // No model configured: use the selected backend's default
  if (!localConfig.model && !globalConfig.model) {
    merged.model = DEFAULT_MODELS[merged.backend] ?? merged.model;
  }

  // API Key resolution: Environment variables always override config file values.
  // Gemini never reads ANTHROPIC_API_KEY, so an Anthropic key is never sent to Google.
  if (merged.backend === 'gemini') {
    merged.apiKey = process.env.GEMINI_API_KEY || process.env.BRIEFED_API_KEY || merged.apiKey || undefined;
  } else {
    merged.apiKey = process.env.BRIEFED_API_KEY || process.env.ANTHROPIC_API_KEY || merged.apiKey || undefined;
  }

  return merged;
}
